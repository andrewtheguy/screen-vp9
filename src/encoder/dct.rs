//!
//! The inverse ones are what a decoder runs, so they are exact to the bit:
//! every value libvpx keeps in 16 bits is wrapped to 16 bits here. Each is
//! written over `Lanes`, so it runs on one value or on a vector of them.

use super::lanes::Lanes;

/// cos(kπ/64) in 14 bits, `COSPI[k]`.
const COSPI: [i32; 32] = [0, 16364, 16305, 16207, 16069, 15893, 15679, 15426, 15137, 14811, 14449, 14053, 13623, 13160, 12665, 12140, 11585, 11003, 10394, 9760, 9102, 8423, 7723, 7005, 6270, 5520, 4756, 3981, 3196, 2404, 1606, 804];

/// The 4-point ADST's sines, sin(kπ/9) scaled, `SINPI[k]`.
const SINPI: [i32; 5] = [0, 5283, 9929, 13377, 15212];

/// libvpx's `dct_const_round_shift`: a product of a `COSPI` back to scale.
#[inline(always)]
fn round14<V: Lanes>(x: V) -> V {
    x.round14()
}

/// A store into a 16-bit value.
#[inline(always)]
fn w<V: Lanes>(x: V) -> V {
    x.wrap16()
}

/// libvpx's `idct4_c`.
#[inline(always)]
pub(super) fn idct4<V: Lanes>(input: &[V; 4], output: &mut [V; 4]) {
    let mut step = [V::splat(0); 4];
    let mut temp1: V;
    let mut temp2: V;
    // stage 1
    temp1 = (input[0] + input[2]) * COSPI[16];
    temp2 = (input[0] - input[2]) * COSPI[16];
    step[0] = w(round14(temp1));
    step[1] = w(round14(temp2));
    temp1 = input[1] * COSPI[24] - input[3] * COSPI[8];
    temp2 = input[1] * COSPI[8] + input[3] * COSPI[24];
    step[2] = w(round14(temp1));
    step[3] = w(round14(temp2));
    // stage 2
    output[0] = w(step[0] + step[3]);
    output[1] = w(step[1] + step[2]);
    output[2] = w(step[1] - step[2]);
    output[3] = w(step[0] - step[3]);
}

/// libvpx's `idct8_c`.
#[inline(always)]
pub(super) fn idct8<V: Lanes>(input: &[V; 8], output: &mut [V; 8]) {
    let mut step1 = [V::splat(0); 8];
    let mut step2 = [V::splat(0); 8];
    let mut temp1: V;
    let mut temp2: V;
    // stage 1
    step1[0] = w(input[0]);
    step1[2] = w(input[4]);
    step1[1] = w(input[2]);
    step1[3] = w(input[6]);
    temp1 = input[1] * COSPI[28] - input[7] * COSPI[4];
    temp2 = input[1] * COSPI[4] + input[7] * COSPI[28];
    step1[4] = w(round14(temp1));
    step1[7] = w(round14(temp2));
    temp1 = input[5] * COSPI[12] - input[3] * COSPI[20];
    temp2 = input[5] * COSPI[20] + input[3] * COSPI[12];
    step1[5] = w(round14(temp1));
    step1[6] = w(round14(temp2));
    // stage 2
    temp1 = (step1[0] + step1[2]) * COSPI[16];
    temp2 = (step1[0] - step1[2]) * COSPI[16];
    step2[0] = w(round14(temp1));
    step2[1] = w(round14(temp2));
    temp1 = step1[1] * COSPI[24] - step1[3] * COSPI[8];
    temp2 = step1[1] * COSPI[8] + step1[3] * COSPI[24];
    step2[2] = w(round14(temp1));
    step2[3] = w(round14(temp2));
    step2[4] = w(step1[4] + step1[5]);
    step2[5] = w(step1[4] - step1[5]);
    step2[6] = w(-step1[6] + step1[7]);
    step2[7] = w(step1[6] + step1[7]);
    // stage 3
    step1[0] = w(step2[0] + step2[3]);
    step1[1] = w(step2[1] + step2[2]);
    step1[2] = w(step2[1] - step2[2]);
    step1[3] = w(step2[0] - step2[3]);
    step1[4] = w(step2[4]);
    temp1 = (step2[6] - step2[5]) * COSPI[16];
    temp2 = (step2[5] + step2[6]) * COSPI[16];
    step1[5] = w(round14(temp1));
    step1[6] = w(round14(temp2));
    step1[7] = w(step2[7]);
    // stage 4
    output[0] = w(step1[0] + step1[7]);
    output[1] = w(step1[1] + step1[6]);
    output[2] = w(step1[2] + step1[5]);
    output[3] = w(step1[3] + step1[4]);
    output[4] = w(step1[3] - step1[4]);
    output[5] = w(step1[2] - step1[5]);
    output[6] = w(step1[1] - step1[6]);
    output[7] = w(step1[0] - step1[7]);
}

